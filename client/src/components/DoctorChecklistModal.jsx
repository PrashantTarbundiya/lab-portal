import { useState, useEffect } from 'react';
import Modal from './Modal';
import Button from './Button';
import LoadingSpinner from './LoadingSpinner';
import { api } from '../utils/api';
import { useAuth } from '../context/AuthContext';
import { useLanguage } from '../context/LanguageContext';

export default function DoctorChecklistModal({ isOpen, onClose, orderId, orderNo, patientName, results = [] }) {
  const [loading, setLoading] = useState(false);
  const [questions, setQuestions] = useState([]);
  const [checkedItems, setCheckedItems] = useState({});
  const [copied, setCopied] = useState(false);

  const { token } = useAuth();
  const { lang } = useLanguage();

  const generateChecklist = async () => {
    setLoading(true);
    try {
      const prompt = 'Please generate exactly 4 clear, high-priority questions that I should ask my doctor during my next consultation regarding these lab results. Format each question on a new line starting with a bullet.';
      const res = await api(`/orders/${orderId}/ask-ai`, {
        method: 'POST',
        body: { question: prompt, lang },
        token,
      });

      if (res.answer) {
        // Parse lines starting with bullet, number, or dash
        const lines = res.answer
          .split('\n')
          .map((l) => l.trim().replace(/^[-*•\d.)\s]+/, '').trim())
          .filter((l) => l.length > 15 && l.includes('?'));

        if (lines.length > 0) {
          setQuestions(lines.slice(0, 5));
          return;
        }
      }
      throw new Error('AI parsing fallback');
    } catch {
      // Smart clinical fallback tailored to abnormal results
      const abnormal = results.filter((r) => r.flag && r.flag !== 'NORMAL');
      const fallbackList = [];

      if (abnormal.length > 0) {
        fallbackList.push(`What is the primary cause of my out-of-range ${abnormal.map((r) => r.parameter).join(', ')}?`);
        fallbackList.push('Should I undergo any repeat lab work or follow-up imaging in 2-4 weeks?');
        fallbackList.push('Are there specific dietary changes, medications, or supplements you recommend for these numbers?');
        fallbackList.push('Are there any warning symptoms (like dizziness, chest pain, or fatigue) that should prompt emergency medical care?');
      } else {
        fallbackList.push('All my parameters appear in normal biological range. Do you recommend continuing my current regimen?');
        fallbackList.push('When is my next routine screening or preventive health checkup due?');
        fallbackList.push('Are there any specific lifestyle or dietary habits I should adjust to maintain these healthy numbers?');
        fallbackList.push('Do my current family medical history risk factors suggest any additional tests?');
      }
      setQuestions(fallbackList);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    if (isOpen && orderId && questions.length === 0) {
      generateChecklist();
    }
  }, [isOpen, orderId]);

  const toggleCheck = (idx) => {
    setCheckedItems((prev) => ({ ...prev, [idx]: !prev[idx] }));
  };

  const handleCopy = () => {
    const text = `Doctor Consultation Checklist - Order #${orderNo} (${patientName})\n\n` +
      questions.map((q, i) => `${checkedItems[i] ? '[X]' : '[ ]'} ${i + 1}. ${q}`).join('\n\n') +
      '\n\nGenerated by Company A Diagnostics Patient Portal';
    navigator.clipboard?.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title="Doctor Consultation Checklist"
      size="md"
    >
      <div className="space-y-4">
        {/* Header Banner */}
        <div className="p-3.5 glass-card bg-emerald-500/10 border border-emerald-500/30 rounded-2xl flex items-center justify-between text-xs">
          <div>
            <span className="text-slate-400 font-mono text-[10px] block">Personalized for:</span>
            <strong className="text-white font-bold">{patientName}</strong> • <span className="font-mono text-emerald-400">Order #{orderNo}</span>
          </div>
          <span className="text-[11px] font-bold text-emerald-300 bg-emerald-500/20 border border-emerald-500/40 px-2 py-0.5 rounded-full">
            AI Generated
          </span>
        </div>

        <p className="text-xs text-slate-300">
          Take these recommended questions to your next appointment. Check them off as you discuss each with your doctor.
        </p>

        {loading ? (
          <div className="py-8 flex flex-col items-center justify-center gap-3">
            <LoadingSpinner size="md" />
            <span className="text-xs text-slate-400 font-medium">Formulating clinical questions...</span>
          </div>
        ) : (
          <div className="space-y-2.5">
            {questions.map((q, idx) => {
              const isChecked = !!checkedItems[idx];
              return (
                <div
                  key={idx}
                  onClick={() => toggleCheck(idx)}
                  className={`p-3.5 rounded-xl border transition-all cursor-pointer flex items-start gap-3 ${
                    isChecked
                      ? 'bg-white/5 border-white/5 opacity-50'
                      : 'glass-card border-white/10 hover:border-emerald-400 hover:bg-white/5 shadow-sm'
                  }`}
                >
                  <input
                    type="checkbox"
                    checked={isChecked}
                    onChange={() => {}}
                    className="mt-0.5 w-4 h-4 rounded text-emerald-500 focus:ring-emerald-400 cursor-pointer"
                  />
                  <div className="flex-1">
                    <p className={`text-xs md:text-sm font-medium ${isChecked ? 'line-through text-slate-500' : 'text-slate-100'}`}>
                      {q}
                    </p>
                  </div>
                </div>
              );
            })}
          </div>
        )}

        {/* Action Buttons */}
        <div className="pt-2 flex flex-wrap items-center justify-between gap-2 border-t border-white/10">
          <Button
            variant="secondary"
            size="sm"
            onClick={generateChecklist}
            loading={loading}
            className="text-xs font-semibold inline-flex items-center gap-1.5"
          >
            <svg className="w-3.5 h-3.5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M4 4v5h.582m15.356 2A8.001 8.001 0 004.582 9m0 0H9m11 11v-5h-.581m0 0a8.003 8.003 0 01-15.357-2m15.357 2H15" /></svg>
            <span>Regenerate</span>
          </Button>

          <div className="flex gap-2">
            <Button
              variant="secondary"
              size="sm"
              onClick={handleCopy}
              className="text-xs font-semibold inline-flex items-center gap-1.5"
            >
              {copied ? (
                <>
                  <svg className="w-3.5 h-3.5 text-emerald-400" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2.5" d="M5 13l4 4L19 7" /></svg>
                  <span>Copied</span>
                </>
              ) : (
                <>
                  <svg className="w-3.5 h-3.5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M8 5H6a2 2 0 00-2 2v12a2 2 0 002 2h10a2 2 0 002-2v-1M8 5a2 2 0 002 2h2a2 2 0 002-2M8 5a2 2 0 012-2h2a2 2 0 012 2m0 0h2a2 2 0 012 2v3m2 4H10m0 0l3-3m-3 3l3 3" /></svg>
                  <span>Copy Checklist</span>
                </>
              )}
            </Button>
            <Button
              variant="primary"
              size="sm"
              onClick={() => window.print()}
              className="text-xs font-semibold inline-flex items-center gap-1.5"
            >
              <svg className="w-3.5 h-3.5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M17 17h2a2 2 0 002-2v-4a2 2 0 00-2-2H5a2 2 0 00-2 2v4a2 2 0 002 2h2m2 4h6a2 2 0 002-2v-4a2 2 0 00-2-2H9a2 2 0 00-2 2v4a2 2 0 002 2zm8-12V5a2 2 0 00-2-2H9a2 2 0 00-2 2v4h10z" /></svg>
              <span>Print Checklist</span>
            </Button>
          </div>
        </div>
      </div>
    </Modal>
  );
}

